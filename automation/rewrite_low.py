def split_lines(text):
    return [l for l in text.split("\n")]


def rebuild(post, ig_body, th_body):
    ig_lines = post["ig_caption"].split("\n")
    cta = [l for l in ig_lines if "App Store" in l or "App Store" in l.replace(" ", "")]
    tags = [l for l in ig_lines if l.strip().startswith("#")]
    if not cta:
        raise SystemExit("CTA行が見つからない: %s" % post.get("app"))
    new_ig = ig_body.split("\n") + [cta[0]] + tags
    post["ig_caption"] = "\n".join(new_ig)

    th_lines = post["threads_text"].split("\n")
    url = [l for l in th_lines if l.strip().startswith("http")]
    th_tags = [l for l in th_lines if l.strip().startswith("#")]
    new_th = th_body.split("\n") + url + th_tags
    post["threads_text"] = "\n".join(new_th)


def main():
    p = ROOT / "post_queue.json"
    q = json.loads(p.read_text(encoding="utf-8"))
    posts = q["posts"]
    banned = ("過去問", "予想問題", "無料", "円", "有料")
    for idx, (ig, th) in sorted(BODY.items()):
        for w in banned:
            if w in ig or w in th:
                raise SystemExit("idx %d に禁止語 %s" % (idx, w))
        rebuild(posts[idx], ig, th)
        print("書き直し idx %-3d %s" % (idx, posts[idx].get("app")))
    p.write_text(json.dumps(q, ensure_ascii=False, indent=2), encoding="utf-8")
    print("\n%d 本を差し替えました。" % len(BODY))


if __name__ == "__main__":
    main()
